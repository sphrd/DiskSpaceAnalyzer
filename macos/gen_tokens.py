#!/usr/bin/env python3
"""Generates Sources/DiskSpaceAnalyzer/Tokens.swift from ../src/Theme.cs, so the macOS app uses exactly the same
colour tokens (including the LOGO_* colours) as the Windows app. src/Theme.cs is the single place to edit them."""
import pathlib
import re

here = pathlib.Path(__file__).resolve().parent
theme = (here.parent / "src" / "Theme.cs").read_text(encoding="utf-8")
out = here / "Sources" / "DiskSpaceAnalyzer" / "Tokens.swift"
# Tokens the macOS app defines itself (extension T in Theme.swift) are not generated again.
own_src = (here / "Sources" / "DiskSpaceAnalyzer" / "Theme.swift").read_text(encoding="utf-8")
own_ext = re.search(r"extension T \{(.*?)\n\}", own_src, re.S)
own = set(re.findall(r"static let (\w+) = rgb\(", own_ext.group(1))) if own_ext else set()

lines = [
    "// GENERATED by macos/gen_tokens.py from src/Theme.cs -- do not edit; edit src/Theme.cs instead.",
    "import AppKit",
    "",
    "enum T {",
]
for name, hexv in re.findall(r"public static readonly Color (\w+) = Hex\(0x([0-9a-fA-F]{6})\);", theme):
    if name in own:
        continue
    lines.append(f"    static let {name} = rgb(0x{hexv.lower()})")
m = re.search(r"public static readonly Color\[\] CHART = \{([^}]*)\}", theme)
if not m:
    raise SystemExit("CHART not found in src/Theme.cs")
chart = ", ".join(f"rgb(0x{h.lower()})" for h in re.findall(r"Hex\(0x([0-9a-fA-F]{6})\)", m.group(1)))
lines.append(f"    static let CHART: [NSColor] = [{chart}]")
lines += [
    "",
    "    static func rgb(_ v: Int) -> NSColor {",
    "        NSColor(srgbRed: CGFloat((v >> 16) & 0xff) / 255, green: CGFloat((v >> 8) & 0xff) / 255,",
    "                blue: CGFloat(v & 0xff) / 255, alpha: 1)",
    "    }",
    "}",
    "",
]
out.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {out.relative_to(here)} ({sum(1 for l in lines if 'static let' in l)} tokens)")
